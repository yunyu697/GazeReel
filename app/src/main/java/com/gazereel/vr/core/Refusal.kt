package com.gazereel.vr.core

/**
 * 19:2x：**明确拒绝**的片源类型。
 *
 * 和「识别不准」是两件事。识别不准时猜一个、给用户一键改；这里的情况是
 * **本工程这一版根本算不出正确的画面**，再猜下去只会把变形画面端上桌，
 * 而用户不知道那是错的 —— 他会以为自己的片子拍坏了，或者以为播放器坏了。
 *
 * 所以这一类的处理是：**不装、明说、给退路**。
 * - 画面降级成 2D 银幕原样显示（至少能看见里头有什么，且不做任何假变换）；
 * - 播放页弹一张常驻卡，说清楚「为什么不支持」；
 * - 卡上写明**怎么才能看**（这次是先在外部缝成等距柱状）。
 *
 * 文案放在 core 而不是绘制层：这类话术会被自检脚本断言，也方便以后加第二种拒绝
 * （例如立方体 / EAC）时保持一个口径。
 */
enum class Refusal(
    /** 写进运行日志的稳定标识，不要改。 */
    val key: String,
    /** 卡上第一行：这是什么。 */
    val title: String,
    /** 卡上第二行：为什么看不了。 */
    val body: String,
    /** 卡上第三行：那我能做什么。句子会按宽度折行，别写太长。 */
    val hint: String
) {
    /**
     * 未缝合的双鱼眼 360（Insta360 / Gear360 / Z CAM 的机内原始片，`.insv` 等）。
     *
     * 画面里左右两个圆是**同一只眼的前后两支镜头**，不是左右眼。
     * 本工程的鱼眼路径是「一只眼一个圆」，拿它去解双鱼眼 360：
     * 每只眼只看得到一个圆（另一半在视野背后），而且前后两圆被当成不同方向的画面，
     * 接缝处永远错位 —— 用户看到的就是「两团圆」。
     *
     * 真正的做法是先按镜头几何缝成等距柱状 360（外部工具一步就能做），
     * 那之后它就是普通的 360 片源，本工程按球面播得很好。
     */
    DUAL_FISHEYE_360(
        key = "dual_fisheye_360",
        title = "未缝合的双鱼眼 360",
        body = "两个圆是同一只眼的前后两支镜头，不是左右眼。",
        hint = "先缝成等距柱状 360（相机 App / ffmpeg v360），现在按 2D 银幕原样显示。"
    );

    companion object {
        fun of(key: String): Refusal? = entries.firstOrNull { it.key == key }
    }
}
